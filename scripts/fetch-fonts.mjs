// Downloads the Google Fonts used by the game into src/ui/fonts (bundled by Vite) so the game works offline (APK/PWA).
// Run: node scripts/fetch-fonts.mjs
import { mkdirSync, writeFileSync } from 'node:fs';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const SHEETS = [
  'https://fonts.googleapis.com/css2?family=Alexandria:wght@400;600;700;800&display=swap',
  'https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@24,500,1,0&icon_names=ac_unit,arrow_back,auto_awesome,bolt,dark_mode,delete,download,explore,favorite,local_fire_department,logout,network_wifi_1_bar,network_wifi_2_bar,network_wifi_3_bar,open_with,pause,play_arrow,replay,settings,shield,signal_wifi_4_bar,speed,swords,volume_off,volume_up,wifi_off&display=block',
];
const KEEP = /^(arabic|latin)$/; // skip cyrillic / latin-ext subsets
const out = 'src/ui/fonts';
mkdirSync(out, { recursive: true });

let css = '/* Self-hosted from Google Fonts (SIL OFL / Apache 2.0). Generated by scripts/fetch-fonts.mjs */\n';
let n = 0;
const files = new Map();
for (const url of SHEETS) {
  const text = await (await fetch(url, { headers: { 'User-Agent': UA } })).text();
  // Blocks look like: /* subset */ @font-face { ... } ; the icon sheet has a single unlabeled block.
  const blocks = text.split('@font-face').slice(1);
  const labels = [...text.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face/g)].map(m => m[1]);
  for (let i = 0; i < blocks.length; i++) {
    const label = labels.length ? labels[i] : 'icons';
    if (labels.length && !KEEP.test(label)) continue;
    const body = blocks[i].slice(0, blocks[i].indexOf('}') + 1);
    const src = body.match(/url\(([^)]+)\)/)[1];
    // Variable fonts serve one file for every weight: download each file once.
    let file = files.get(src);
    if (!file) {
      file = `f${n++}.woff2`; files.set(src, file);
      writeFileSync(`${out}/${file}`, Buffer.from(await (await fetch(src, { headers: { 'User-Agent': UA } })).arrayBuffer()));
    }
    css += `@font-face${body.replace(src, file)}\n`;
  }
  if (url.includes('Material')) {
    css += `.ic{font-family:'Material Symbols Rounded';font-weight:normal;font-style:normal;font-size:1.2em;line-height:1;letter-spacing:normal;text-transform:none;display:inline-block;white-space:nowrap;direction:ltr;-webkit-font-feature-settings:'liga';font-feature-settings:'liga';-webkit-font-smoothing:antialiased;font-variation-settings:'FILL' 1,'wght' 500}\n`;
  }
}
writeFileSync(`${out}/fonts.css`, css);
console.log(`saved ${n} font files to ${out}`);
